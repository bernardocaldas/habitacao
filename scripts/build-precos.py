"""Generate src/data/precos.ts from src/data/fontes/ine.json (INE and ECB series).

Run from the repository root:  python3 -I scripts/build-precos.py

What it does, so the numbers can be checked:
- Sale prices: INE median €/m² of dwellings sold, by parish, one value per year (the 12
  months to Q4), placed at mid-year. The rolling 12 months to 2026 Q1 is added at Oct 2025.
- Rents: INE median €/m² of new leases, by parish, per year, at mid-year; the rolling 12
  months to 2026 Q2 is added at Jan 2026.
- For the economy, each parish is Lisboa's value times the parish/Lisboa ratio averaged over
  three years, because parish medians jump from year to year (a single development can move
  one). The map shows INE's own annual figure.
- 2015 (and rents for 2015-16) have no INE parish data: they are backcast from Lisboa's
  2016-17 growth and flagged as estimates. After the last INE point, prices follow a stated
  scenario (+5%/yr sales, +3%/yr rents), flagged as a scenario.
"""
import json

SRC = 'src/data/fontes/ine.json'
OUT = 'src/data/precos.ts'
d = json.load(open(SRC, encoding='utf-8'))
codes = sorted(k for k in d['sale_eur_m2'] if k != '1106')

def series(key, latest_key, latest_at, first_year):
    out = {}
    for code, row in d[key].items():
        pts = [(int(y) + 0.5, v) for y, v in row.items() if v is not None and int(y) >= first_year]
        lv = d.get(latest_key, {}).get(code)
        if isinstance(lv, (int, float)):
            pts.append((latest_at, lv))
        out[code] = sorted(pts)
    return out

sale = series('sale_eur_m2', 'sale_eur_m2_12m_to_2026Q1', 2025.8, 2016)
rent = series('rent_eur_m2', 'rent_eur_m2_12m_to_2026Q2', 2026.0, 2017)

def smooth(s, code):
    lis = dict(s['1106'])
    par = dict(s[code])
    xs = sorted(lis)
    rel = {x: par[x] / lis[x] for x in xs if x in par}
    keys = sorted(rel)
    sm = {}
    for i, x in enumerate(keys):
        win = [rel[k] for k in keys[max(0, i - 1): i + 2]]
        sm[x] = sum(win) / len(win)
    return [[x, round(lis[x] * sm[x], 2 if lis[x] < 100 else 0)] for x in keys]

def backcast(pts, years, growth):
    # Prepend estimates before the first INE point by undoing Lisboa-style growth.
    first_x, first_v = pts[0]
    pre = []
    for k in range(years, 0, -1):
        pre.append([first_x - k, round(first_v / (growth ** k), 2 if first_v < 100 else 0)])
    return pre

lines = []
w = lines.append
w('// GENERATED by scripts/build-precos.py from src/data/fontes/ine.json. Do not edit by hand.')
w('//')
w('// Sale: INE median value of dwellings sold, €/m² (indicators 0010033 to 2018, 0012255 from')
w('// 2019; 12 months to Q4), plus the 12 months to 2026 Q1 (0012234). Rent: INE median rent of')
w('// new leases, €/m² (0009631 to 2019, 0014698 from 2020), plus the 12 months to 2026 Q2')
w('// (0014696). Smoothed series (SALE/RENT) feed the economy; RAW_* are INE\'s own figures.')
w("import type { Lang } from '../sim/types';")
w('')
w('type Pt = [year: number, value: number];')
w('')
lis_sale_growth = d['sale_eur_m2']['1106']['2017'] / d['sale_eur_m2']['1106']['2016']
lis_rent_growth = d['rent_eur_m2']['1106']['2018'] / d['rent_eur_m2']['1106']['2017']
w(f'/** Lisboa\'s 2016-17 growth, used to backcast 2015 (sales) and 2015-16 (rents). */')
w(f'export const BACKCAST = {{ sale: {lis_sale_growth:.4f}, rent: {lis_rent_growth:.4f} }};')
w('export const SCENARIO = { sale: 0.05, rent: 0.03 };')
w('')
for name, s, years, g in (('SALE', sale, 1, lis_sale_growth), ('RENT', rent, 2, lis_rent_growth)):
    w(f'const {name}: Record<string, Pt[]> = {{')
    for code in ['1106'] + codes:
        pts = s[code] if code == '1106' else smooth(s, code)
        pts = backcast(pts, years, g) + pts
        w(f"  '{code}': {json.dumps(pts)},")
    w('};')
    w('')
for name, key in (('RAW_SALE', 'sale_eur_m2'), ('RAW_RENT', 'rent_eur_m2')):
    w(f'const {name}: Record<string, Record<number, number>> = {{')
    for code in ['1106'] + codes:
        row = {int(y): v for y, v in d[key][code].items() if v is not None}
        w(f"  '{code}': {json.dumps(row)},")
    w('};')
    w('')
al = d['al']
w('/** Active short-let registrations (RNAL, snapshot of 10 October 2026) and the share of')
w(' * 2021 Census dwellings they represent (our calculation, the definition the city uses). */')
w('export const AL_COUNTS: Record<string, { n: number; pct: number }> = {')
for code in codes:
    a = al[code]
    w(f"  '{code}': {{ n: {a['registrations']}, pct: {a['ratio_pct']} }},")
w('};')
w('')
w('export const LAST_DATA = { sale: %s, rent: %s };' % (max(x for x, _ in sale['1106']), max(x for x, _ in rent['1106'])))
w('''
function interp(s: Pt[], y: number, growth: number): number {
  if (y <= s[0][0]) return s[0][1];
  for (let i = 1; i < s.length; i++) {
    if (y <= s[i][0]) {
      const [a, va] = s[i - 1], [b, vb] = s[i];
      return va + ((vb - va) * (y - a)) / (b - a);
    }
  }
  const [last, v] = s[s.length - 1];
  return v * Math.pow(1 + growth, y - last);
}

/** Median sale price, €/m², at a fractional year (smoothed by parish; scenario after the data). */
export const priceM2 = (code: string, year: number) => interp(SALE[code] ?? SALE['1106'], year, SCENARIO.sale);
/** Median rent of new leases, €/m²/month, at a fractional year. */
export const rentM2 = (code: string, year: number) => interp(RENT[code] ?? RENT['1106'], year, SCENARIO.rent);
export const lisboaPriceM2 = (year: number) => interp(SALE['1106'], year, SCENARIO.sale);

/** INE's own median rent of new leases for a year, when published. */
export const rawRent = (code: string, year: number): number | undefined => RAW_RENT[code]?.[Math.floor(year)];

export type Provenance = 'ine' | 'estimativa' | 'cenario';

/** INE's own annual figure where there is one; otherwise the game's estimate or scenario. */
export function rawPrice(code: string, year: number): { value: number; kind: Provenance } {
  const y = Math.floor(year);
  const v = RAW_SALE[code]?.[y];
  if (v != null) return { value: v, kind: 'ine' };
  return { value: priceM2(code, y + 0.5), kind: y < 2016 ? 'estimativa' : 'cenario' };
}

export const PROVENANCE_LABEL: Record<Provenance, Record<Lang, string>> = {
  ine: { pt: 'INE', en: 'INE' },
  estimativa: { pt: 'estimativa', en: 'estimate' },
  cenario: { pt: 'cenário', en: 'scenario' },
};
''')
open(OUT, 'w', encoding='utf-8').write('\n'.join(lines))
print('wrote', OUT)
